def generate_radical_riddles():
    entries = []
    for radical, radical_name, chars in LR_CHARS:
        for component, result in chars:
            entries.append((f"{radical_name}加个{component}", result))
            entries.append((f"{radical}加{component}是什么字", result))
    for radical, radical_name, chars in TB_CHARS:
        for component, result in chars:
            entries.append((f"{radical_name}下面有个{component}", result))
    return entries


def get_all_riddles():
    all_entries = []
    all_entries.extend(EXTRA_RIDDLES)
    all_entries.extend(ADDITIONAL_CLASSIC)
    all_entries.extend(generate_radical_riddles())

    unique = []
    seen = set()
    for q, a in all_entries:
        key = f"{q}|{a}"
        if key not in seen:
            seen.add(key)
            unique.append((q, a))

    return unique


def main():
    if not os.path.exists(DB_PATH):
        print(f"数据库不存在: {DB_PATH}")
        sys.exit(1)

    existing_hashes = get_all_hashes(DB_PATH)
    current = get_count(DB_PATH, CATEGORY)
    print(f"[word_puzzle] 当前 {current} 条，目标 {TARGET} 条")
    need = TARGET - current
    if need <= 0:
        print("已达标")
        return

    print(f"还需 {need} 条\n")

    riddles = get_all_riddles()
    print(f"生成补充字谜总数: {len(riddles)} 条")

    random.shuffle(riddles)

    batch_size = 500
    total_added = 0
    for i in range(0, len(riddles), batch_size):
        batch = riddles[i:i + batch_size]
        added = insert_batch(DB_PATH, batch, CATEGORY, existing_hashes)
        total_added += added
        current = get_count(DB_PATH, CATEGORY)
        print(f"  批次 {i // batch_size + 1}: 新增 {added} 条, 总计 {current}/{TARGET}")
        if current >= TARGET:
            break

    print(f"\n最终: 新增 {total_added} 条, 总计 {get_count(DB_PATH, CATEGORY)} 条")


if __name__ == "__main__":
    main()
