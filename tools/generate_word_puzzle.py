def get_all_riddles():
    all_entries = []
    all_entries.extend(CURATED_RIDDLES)
    all_entries.extend(STRUCTURE_RIDDLES)
    all_entries.extend(COUNTING_RIDDLES)
    all_entries.extend(SUBTRACTION_MORE)
    all_entries.extend(ARITHMETIC_MORE)
    all_entries.extend(MEANING_RIDDLES)
    all_entries.extend(HOMOPHONE_RIDDLES)
    all_entries.extend(TIME_RIDDLES)

    unique = []
    seen = set()
    for q, a in all_entries:
        key = f"{q}|{a}"
        if key not in seen:
            seen.add(key)
            unique.append((q, a))

    return unique


