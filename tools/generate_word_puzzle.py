def generate_hash(question, answer):
    return hashlib.md5(f"{question}|{answer}".encode()).hexdigest()


def sanitize(text):
    """替换文本中的 --- 和 -- 为 ——，避免与分隔符冲突。"""
    return text.replace("---", "——").replace("--", "——").strip()


def load_existing():
    """从已有的 txt 文件中加载 hash 集合和条目数。"""
    hashes = set()
    count = 0
    if not os.path.exists(OUTPUT_PATH):
        return hashes, count
    with open(OUTPUT_PATH, "r", encoding="utf-8") as f:
        content = f.read()
    for chunk in content.split("---"):
        chunk = chunk.strip()
        if not chunk:
            continue
        lines = chunk.split("\n", 1)
        q = lines[0].replace("问题：", "").strip() if lines else ""
        a = lines[1].replace("答案:", "").strip() if len(lines) > 1 else ""
        if q and a:
            hashes.add(generate_hash(q, a))
            count += 1
    return hashes, count


def append_entries(entries, existing_hashes):
    """将新条目追加写入 txt 文件，返回实际新增数量。"""
    added = 0
    with open(OUTPUT_PATH, "a", encoding="utf-8") as f:
        for q, a in entries:
            q, a = sanitize(q), sanitize(a)
            h = generate_hash(q, a)
            if h in existing_hashes:
                continue
            existing_hashes.add(h)
            f.write(f"问题：{q}\n答案:{a}\n---\n")
            added += 1
    return added


