def main():
    existing_hashes, current = load_existing()
    print(f"[trivia] 当前 {current} 条，目标 {TARGET} 条")
    print(f"已有 {len(existing_hashes)} 个唯一条目")

    if current >= TARGET:
        print("已达标，无需生成")
        return

    generators = [
        ("中国省份", china_provinces),
        ("世界国家", world_countries),
        ("中国地理", chinese_geography),
        ("太阳系", solar_system),
        ("化学", chemistry),
        ("中国历史", chinese_history),
        ("动物", animals),
        ("植物", plants),
        ("科学", science),
        ("文化", culture),
        ("数学", math_facts),
        ("生活常识", daily_life),
        ("世界之最", world_records),
        ("营养健康", food_nutrition),
        ("科技", technology),
        ("体育", sports_facts),
        ("环境", environment),
        ("音乐美术", music_art),
        ("补充知识", extra_knowledge),
    ]

    all_entries = []
    for name, gen_fn in generators:
        entries = gen_fn()
        all_entries.extend(entries)
        print(f"  {name}: {len(entries)} 条")

    random.shuffle(all_entries)

    unique = []
    seen = set()
    for q, a in all_entries:
        key = f"{q}|{a}"
        if key not in seen:
            seen.add(key)
            unique.append((q, a))

    print(f"\n去重后共 {len(unique)} 条")

    added = append_entries(unique, existing_hashes)
    final = current + added
    print(f"新增 {added} 条，当前总计 {final} 条")

    if final < TARGET:
        print(f"\n[WARN] 仍需 {TARGET - final} 条，请补充更多数据")


if __name__ == "__main__":
    main()
