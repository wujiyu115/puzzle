def main():
    if not os.path.exists(DB_PATH):
        print(f"数据库不存在: {DB_PATH}")
        sys.exit(1)

    existing_hashes = get_all_hashes(DB_PATH)
    current = get_count(DB_PATH, CATEGORY)
    print(f"[word_puzzle] 当前 {current} 条，目标 {TARGET} 条")
    need = TARGET - current
    if need <= 0:
        print("已达标")
        return

    print(f"还需 {need} 条\n")

    riddles = BATCH3_RIDDLES
    seen = set()
    unique = []
    for q, a in riddles:
        key = f"{q}|{a}"
        if key not in seen:
            seen.add(key)
            unique.append((q, a))

    print(f"第三批字谜总数: {len(unique)} 条")

    random.shuffle(unique)

    added = insert_batch(DB_PATH, unique, CATEGORY, existing_hashes)
    current = get_count(DB_PATH, CATEGORY)
    print(f"  新增 {added} 条, 总计 {current}/{TARGET}")

    print(f"\n最终: 新增 {added} 条, 总计 {get_count(DB_PATH, CATEGORY)} 条")


if __name__ == "__main__":
    main()
